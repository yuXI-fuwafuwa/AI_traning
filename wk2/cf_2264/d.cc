#include <bits/stdc++.h>

using i64 = long long;
using u64 = unsigned long long;

void solve(int n)
{
    auto nxt = [](u64 x)
    {
        u64 r = x + (x & -x);
        return r | (((x ^ r) >> 2) / (x & -x));
    };

    i64 fans = (i64)n * n;
    std::vector<u64> res;

    auto getf = [&](int k)
    {
        u64 up = (1ull << n);
        for (u64 u = (1ull << k) - 1; u < up; u = nxt(u))
        {
            i64 f = 0;
            for (int l = 0; l < n; ++l) for (int r = l; r < n; ++r)
            {
                u64 mask = (1ull << (r - l + 1)) - 1;
                u64 x = (u >> l) & mask;
                if (x % 3 == 0) ++f;
            }
            if (f < fans)
            {
                fans = f;
                res.clear();
                res.push_back(u);
            }
            else if (f == fans)
                res.push_back(u);
        }
    };
    getf(1), getf(2), getf(3);

    // std::cout << fans << '\n';
    // std::cout << res.size() << '\n';
    // // for (auto v : res)
    // //     std::cout << std::bitset<64>(v) << '\n';
    // if (res.size()) std::cout << std::bitset<64>(res[0]) << '\n';
    // std::cout << "\n==============================\n";

    std::sort(res.begin(), res.end());

    if (res.size())
        std::cout << std::bitset<64>(res[0]) << "\n";
}

void real_solve()
{
    int n;
    std::cin >> n;

    if (n <= 4)
    {
        if (n == 1) std::cout << "1\n";
        else if (n == 2) std::cout << "01\n";
        else if (n == 3) std::cout << "101\n";
        else if (n == 4) std::cout << "0101\n";
        return;
    }

    int group = (n - 5) / 6;
    int posit = (n - 5) % 6;

    std::string res(n, '0');

    int cntz = group * 2 + 1;
    if (posit == 0 || posit == 1)
        res[cntz] = '1', res[cntz * 2 + 1] = '1';
    else if (posit == 2)
        res[cntz + 1] = '1', res[(cntz + 1) * 2] = '1';
    else if (posit == 3 || posit == 4)
        res[0] = '1', res[cntz + 2] = '1', res[cntz * 2 + 3] = '1';
    else if (posit == 5)
        res[cntz + 1] = '1', res[cntz * 2 + 4] = '1';

    std::cout << std::string(res.rbegin(), res.rend()) << '\n';
}

